//! The measurement behind dir packs and parallel uploads: a `node_modules` shaped like pnpm's
//! (`.pnpm/<pkg>@<v>/node_modules/<pkg>/…` plus a symlink per package, thousands of small
//! directories and files, a few large binaries) behind a sink that spends a fixed latency on
//! every request, as a presigned PUT or GET from a MicroVM to S3 does (≈ 70 ms measured on alpha).
//!
//! `cargo test -p sealant-capture --release --test node_modules_measure -- --ignored --nocapture`
//!
//! Scale and latency: `CAPTURE_MEASURE_PACKAGES` (default 1000; six directories and twenty files
//! each), `CAPTURE_MEASURE_LATENCY_MS` (default 40). Only public API present before dir packs is
//! used, so the same file runs against the previous release for the "before" numbers.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::Arc;
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{Duration, Instant};

use sealant_capture::sink::{BlobSource, PutOutcome, SinkError};
use sealant_capture::{
    BlobSink, CaptureConfig, CaptureEngine, CaptureKind, Class, InMemoryRegistrar, LocalDir,
    MaterializeClass, MaterializeTargets, Materializer, Registrar, SnapRequest,
};

fn git(root: &Path, args: &[&str]) {
    let out = Command::new("git")
        .current_dir(root)
        .env("GIT_OPTIONAL_LOCKS", "0")
        .args(args)
        .output()
        .expect("git");
    assert!(
        out.status.success(),
        "git {args:?} failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );
}

fn env_or(name: &str, default: u64) -> u64 {
    std::env::var(name)
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(default)
}

fn pseudo_random(len: usize, seed: u64) -> Vec<u8> {
    let mut x = seed | 1;
    (0..len)
        .map(|_| {
            x ^= x << 13;
            x ^= x >> 7;
            x ^= x << 17;
            (x >> 24 & 0xff) as u8
        })
        .collect()
}

/// A repository whose ignored `node_modules/` is pnpm-shaped: per package six directories
/// (`.pnpm/<pkg>@1.0.0`, its `node_modules`, the package, `lib`, `lib/util`, `dist`), twenty
/// small files and a top-level symlink; three packages carry a 6 MiB binary.
fn workspace(root: &Path, packages: usize) {
    fs::create_dir_all(root.join("src")).unwrap();
    git(root, &["init", "-q", "-b", "main"]);
    git(root, &["config", "user.email", "t@t"]);
    git(root, &["config", "user.name", "t"]);
    fs::write(root.join(".gitignore"), "node_modules/\n").unwrap();
    fs::write(root.join("src/lib.rs"), "pub fn f() {}\n").unwrap();
    git(root, &["add", "-A"]);
    git(root, &["commit", "-q", "-m", "one"]);
    let nm = root.join("node_modules");
    for p in 0..packages {
        let name = format!("pkg{p}");
        let pkg = nm
            .join(".pnpm")
            .join(format!("{name}@1.0.0"))
            .join("node_modules")
            .join(&name);
        fs::create_dir_all(pkg.join("lib/util")).unwrap();
        fs::create_dir_all(pkg.join("dist")).unwrap();
        fs::write(
            pkg.join("package.json"),
            format!("{{\"name\":\"{name}\",\"version\":\"1.0.0\",\"main\":\"lib/index.js\"}}\n"),
        )
        .unwrap();
        fs::write(pkg.join("README.md"), format!("# {name}\n\nA package.\n")).unwrap();
        for f in 0..6 {
            fs::write(
                pkg.join(format!("lib/m{f}.js")),
                format!("exports.m{f} = function () {{ return [{p}, {f}]; }};\n").repeat(6),
            )
            .unwrap();
            fs::write(
                pkg.join(format!("lib/util/u{f}.js")),
                format!("module.exports = {{ u: {p}, f: {f} }};\n").repeat(4),
            )
            .unwrap();
            fs::write(
                pkg.join(format!("dist/d{f}.cjs")),
                format!("\"use strict\";exports.d={p}*{f};\n").repeat(10),
            )
            .unwrap();
        }
        if p % (packages / 3).max(1) == 0 && p / (packages / 3).max(1) < 3 {
            fs::write(
                pkg.join("dist/native.node"),
                pseudo_random(6 * 1024 * 1024, p as u64 + 7),
            )
            .unwrap();
        }
        std::os::unix::fs::symlink(
            format!(".pnpm/{name}@1.0.0/node_modules/{name}"),
            nm.join(&name),
        )
        .unwrap();
    }
}

#[derive(Default)]
struct Counts {
    puts: AtomicU64,
    gets: AtomicU64,
    exists: AtomicU64,
    mints: AtomicU64,
}

impl Counts {
    fn take(&self) -> [u64; 4] {
        [
            self.puts.swap(0, Ordering::SeqCst),
            self.gets.swap(0, Ordering::SeqCst),
            self.exists.swap(0, Ordering::SeqCst),
            self.mints.swap(0, Ordering::SeqCst),
        ]
    }
}

/// A directory store that spends `latency` on every request, and counts them. A batch URL mint
/// (`prefetch_put`, one `upload.urls` call) is a request too.
struct SlowSink {
    inner: LocalDir,
    latency: Duration,
    counts: Arc<Counts>,
}

impl BlobSink for SlowSink {
    fn put_if_absent(&self, key: &str, source: BlobSource<'_>) -> Result<PutOutcome, SinkError> {
        self.counts.puts.fetch_add(1, Ordering::SeqCst);
        std::thread::sleep(self.latency);
        self.inner.put_if_absent(key, source)
    }

    fn prefetch_put(&self, keys: &[(String, u64)]) -> Result<(), SinkError> {
        if !keys.is_empty() {
            self.counts.mints.fetch_add(1, Ordering::SeqCst);
            std::thread::sleep(self.latency);
        }
        Ok(())
    }

    fn get(&self, key: &str) -> Result<Vec<u8>, SinkError> {
        self.counts.gets.fetch_add(1, Ordering::SeqCst);
        std::thread::sleep(self.latency);
        self.inner.get(key)
    }

    fn exists(&self, key: &str) -> Result<bool, SinkError> {
        self.counts.exists.fetch_add(1, Ordering::SeqCst);
        std::thread::sleep(self.latency);
        self.inner.exists(key)
    }
}

fn row(step: &str, counts: [u64; 4], wall: Duration) {
    let [puts, gets, exists, mints] = counts;
    println!(
        "{step:<28} {:>7} {puts:>7} {gets:>7} {exists:>7} {mints:>7} {:>10.2}",
        puts + gets + exists + mints,
        wall.as_secs_f64()
    );
}

#[test]
#[ignore = "a measurement: minutes at 40 ms per request; run with --ignored --nocapture"]
fn node_modules_capture_ship_and_materialize() {
    let packages = usize::try_from(env_or("CAPTURE_MEASURE_PACKAGES", 1000)).unwrap_or(1000);
    let latency = Duration::from_millis(env_or("CAPTURE_MEASURE_LATENCY_MS", 40));
    let tmp = tempfile::tempdir().unwrap();
    let base: PathBuf = tmp.path().to_path_buf();
    let root = base.join("ws");
    workspace(&root, packages);
    let counts = Arc::new(Counts::default());
    let slow = Arc::new(SlowSink {
        inner: LocalDir::new(&base.join("store")).unwrap(),
        latency,
        counts: counts.clone(),
    });
    let sink: Arc<dyn BlobSink> = slow.clone();
    let registrar = Arc::new(InMemoryRegistrar::new("wt", 1, None));
    let dyn_registrar: Arc<dyn Registrar> = registrar.clone();
    let mut engine = CaptureEngine::open(CaptureConfig::new("wt", 1, &root), None).unwrap();
    let shipper = engine.shipper(sink.clone(), dyn_registrar);

    println!(
        "\n{packages} packages ({} dirs, {} files under node_modules), {} ms per request",
        packages * 6 + 2,
        packages * 20 + 3,
        latency.as_millis()
    );
    println!(
        "{:<28} {:>7} {:>7} {:>7} {:>7} {:>7} {:>10}",
        "step", "total", "PUT", "GET", "HEAD", "mint", "wall s"
    );
    let snap = |engine: &mut CaptureEngine, class: Class, seq: u64| {
        engine
            .snap(SnapRequest {
                kind: CaptureKind::Auto,
                class,
                seq,
            })
            .unwrap()
    };

    let t = Instant::now();
    snap(&mut engine, Class::Small, 1);
    shipper.ship_pending().unwrap();
    row("small capture + ship", counts.take(), t.elapsed());

    let t = Instant::now();
    let bulk = snap(&mut engine, Class::Bulk, 2);
    let snapped = t.elapsed();
    let t = Instant::now();
    shipper.ship_pending().unwrap();
    let shipped = t.elapsed();
    println!(
        "bulk snap {:.2} s: {}",
        snapped.as_secs_f64(),
        serde_json::to_string(&bulk.stats).unwrap()
    );
    row("first bulk capture: ship", counts.take(), shipped);

    // One edit deep in the tree: the Merkle path of changed directories and one chunk.
    let edited = root.join(format!(
        "node_modules/.pnpm/pkg{0}@1.0.0/node_modules/pkg{0}/lib/util/u3.js",
        packages / 2
    ));
    fs::write(&edited, "module.exports = 'edited';\n").unwrap();
    let t = Instant::now();
    let inc = snap(&mut engine, Class::Bulk, 3);
    let snapped = t.elapsed();
    let t = Instant::now();
    shipper.ship_pending().unwrap();
    let shipped = t.elapsed();
    println!(
        "incremental snap {:.2} s: {}",
        snapped.as_secs_f64(),
        serde_json::to_string(&inc.stats).unwrap()
    );
    row("one edit: ship", counts.take(), shipped);

    let head = registrar.head().unwrap();
    let restore = base.join("restore");
    let t = Instant::now();
    let report = Materializer::new(
        sink.as_ref(),
        MaterializeTargets::new(&restore, Some(base.join("home2"))),
    )
    .materialize(&head.manifest, MaterializeClass::All)
    .unwrap();
    row("full materialize", counts.take(), t.elapsed());
    println!("materialize: {report:?}");
    assert_eq!(
        fs::read_to_string(restore.join(edited.strip_prefix(&root).unwrap())).unwrap(),
        "module.exports = 'edited';\n"
    );
    assert!(
        fs::symlink_metadata(restore.join("node_modules/pkg0"))
            .unwrap()
            .file_type()
            .is_symlink()
    );
}
